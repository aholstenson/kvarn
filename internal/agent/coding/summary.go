// notProvided stands in for a required section the agent left empty even after
// being asked again. The section is rendered rather than dropped so a reviewer
// sees the gap instead of a body that looks complete.
const notProvided = "_(not provided)_"

// summarySystemPrompt builds the system prompt for the summary call: who is
// writing, whose conventions apply, and the repository's own instruction file
// as a last resort for conventions nobody stated explicitly.
//
// The role names both readers of the text on purpose. The call continues the
// coding conversation, whose last turns are mostly test and build runs, and a
// model told to summarize "work" reports those runs. Naming the reviewer and the
// reader of the history points it at the change instead.
//
// Configured instructions are labelled by origin. An operator's house style and
// a repository's local rules are both in force, and when they pull in different
// directions the model can at least see which is which.
func summarySystemPrompt(content forgeconfig.Content, repoInstructions string) string {
	var sb strings.Builder
	sb.WriteString("You write the commit message and pull request description for a code change. " +
		"Two people read the text: a reviewer who decides whether to merge the change, and, later, " +
		"someone who reads the history to learn why the code is the way it is. " +
		"The text explains the change. It is not a report of the work that produced it.")

	writeInstructionBlock(&sb, "Organization conventions", content.TitleInstructions.Organization,
		content.BodyInstructions.Organization)
	writeInstructionBlock(&sb, "Repository conventions", content.TitleInstructions.Repository,
		content.BodyInstructions.Repository)

	if repoInstructions != "" {
		sb.WriteString("\n\nThe following project instructions may contain commit message conventions you should follow:\n\n")
		sb.WriteString(repoInstructions)
	}
	return sb.String()
}

// writeInstructionBlock appends one labelled instruction section, skipping it
// when every part is empty.
func writeInstructionBlock(sb *strings.Builder, heading string, parts ...string) {
	var kept []string
	for _, p := range parts {
		if p = strings.TrimSpace(p); p != "" {
			kept = append(kept, p)
		}
	}
	if len(kept) == 0 {
		return
	}
	fmt.Fprintf(sb, "\n\n## %s\n\n", heading)
	sb.WriteString(strings.Join(kept, "\n\n"))
}

// descriptionRules is what a description contains and how it reads. The first
// summary and every revision state the same rules, so the text a revision keeps
// and the text it writes follow one standard.
//
// The description is the commit body a squash merge records, so the rules keep
// out everything that is true only during review: how the change was tested,
// what the agent tried, problems the change does not touch. Testing notes still
// have a place when a repository declares a section for them.
//
// The footer prohibition is deliberate: a run's identity footer and commit
// trailers are appended by kvarn after the fact, where they are exact, so a
// model-written one would only duplicate them.
const descriptionRules = `Writing the description:

The description becomes the commit message body when the pull request is merged. It must stay true and useful long after review.

Include, in this order:
- Why: the problem or need the change answers. Take it from the task and the conversation. Do not invent a reason. One to three sentences.
- What: what the code does now, as behavior and approach, at the level a reviewer needs before reading the diff.
- Decisions a reviewer cannot see in the diff, if there are any: trade-offs, alternatives rejected and why, limits on what the change covers, safety measures, how it rolls out (feature flags, migrations, configuration), and compatibility.

Leave out:
- How the change was tested or verified: test runs, test counts, linters, builds, manual checks. If a requested section asks for this, put it in that section.
- Problems that existed before the change and that it does not touch.
- The process: what you tried first, what you examined, how you got to the result.
- Implementation details that a reader of the diff sees at once, unless they are a risk the reviewer must check.
- A list of the files changed.
- A footer such as "Generated by" or a session id.

Form:
- Use present tense for what the code does ("The client retries a failed request with backoff"), not past tense for what you did ("Added retries").
- Fit the length to the change. A small fix needs one or two sentences. A large feature can need several paragraphs. Do not pad.
- Write plain paragraphs and wrap lines at about 72 characters. Use a short bullet list only for items that are parallel. Do not use headings.
- Do not repeat the title.
`

// summaryPrompt is the trailing user turn that asks for the commit/PR summary.
func summaryPrompt(content forgeconfig.Content, recentCommits []string) string {
	var sb strings.Builder
	sb.WriteString("Write the commit message and pull request description for the change you just made.\n\n")
	sb.WriteString("Provide, in this order:\n")
	sb.WriteString("- description: the commit body, which is also the pull request description. " +
		"Follow the rules under \"Writing the description\" below.\n")

	if len(content.BodySections) > 0 {
		sb.WriteString("- sections: one entry per requested section below, each with the name exactly as given " +
			"and markdown content. Do not invent sections that are not listed. " +
			"Keep this material out of the description; it belongs in its own section.\n")
	} else {
		sb.WriteString("- sections: leave empty; none are requested.\n")
	}

	fmt.Fprintf(&sb, "- title: an imperative-mood subject line naming the change you just described, "+
		"max %d chars, no trailing period. Write the real title; there is no later pass to fix it up.\n",
		content.TitleMaxLength)

	sb.WriteString("\n")
	sb.WriteString(descriptionRules)

	if len(content.BodySections) > 0 {
		sb.WriteString("\nRequested sections:\n")
		writeSectionRequests(&sb, content.BodySections)
	}

	if len(recentCommits) > 0 {
		sb.WriteString("\nMatch the commit message style used in this repository. Here are recent commit titles for reference:\n")
		for _, commit := range recentCommits {
			sb.WriteString("- ")
			sb.WriteString(commit)
			sb.WriteString("\n")
		}
	}
	return sb.String()
}

// revisionDiffCap bounds the diff a revision prompt carries. The run's own
// history already holds the change in detail, so the diff is there to show the
// pull request as a whole, and its first part is enough for that. The whole
// diff can be several times this, which would cost more than the revision is
// worth.
const revisionDiffCap = 64 * 1024

// revisionPrompt is the trailing user turn that asks for a revised title and
// description of the pull request the run committed onto.
//
// The rules it states are the reason the feature exists. A squash merge takes
// its message from the title and description, so they must describe the
// result, not how review got there; and a person has already read the current
// text, so it changes only where it became wrong.
//
// Text that breaks descriptionRules counts as wrong, because it is what goes
// stale first: a test count describes the commit it was written for. Text that
// only differs in style is kept, so a revision does not rewrite a correct
// description that a reviewer has already read.
func revisionPrompt(content forgeconfig.Content, in agent.PullRequestRevision) string {
	var sb strings.Builder
	sb.WriteString("The commit you just made was pushed onto an existing pull request. " +
		"Its title and description were written for the change as it stood before your commit, " +
		"and may now be wrong or incomplete. A squash merge uses them as the commit message, " +
		"so they must describe the whole pull request as it stands now.\n\n")

	sb.WriteString("Current title:\n\n")
	sb.WriteString(strings.TrimSpace(in.Title))
	sb.WriteString("\n\nCurrent description:\n\n<description>\n")
	sb.WriteString(strings.TrimSpace(in.Description))
	sb.WriteString("\n</description>\n")

	if diff := strings.TrimSpace(in.Diff); diff != "" {
		truncated := false
		if len(diff) > revisionDiffCap {
			diff = strings.ToValidUTF8(diff[:revisionDiffCap], "")
			truncated = true
		}
		sb.WriteString("\nThe pull request's diff as it stands now, including your commit:\n\n```diff\n")
		sb.WriteString(diff)
		sb.WriteString("\n```\n")
		if truncated {
			sb.WriteString("\nThe diff is truncated. Use what you know of the change for the rest.\n")
		}
	}

	sb.WriteString("\nRevise the title and description:\n")
	sb.WriteString("- Keep all text that is still correct, word for word. Change only what your commit made " +
		"wrong or incomplete. If nothing is wrong, return the current text unchanged.\n")
	sb.WriteString("- Text in the description that \"Writing the description\" below says to leave out is not correct, " +
		"for example a note on how an earlier commit was tested. Remove it. " +
		"Do not rewrite correct text only to change its tense or style.\n")
	sb.WriteString("- Describe the result, not the review. Do not write \"addressed feedback\", " +
		"\"updated per review\" or a list of revisions.\n")

	if len(content.BodySections) > 0 {
		sb.WriteString("- description: the text of the current description above its first requested section, " +
			"revised.\n")
		sb.WriteString("- sections: one entry per requested section below, each with the name exactly as given. " +
			"Start from that section's current content.\n")
	} else {
		sb.WriteString("- description: the current description, revised.\n")
		sb.WriteString("- sections: leave empty; none are requested.\n")
	}

	fmt.Fprintf(&sb, "- title: the current title, unless it no longer names the change. "+
		"Imperative mood, max %d chars, no trailing period.\n", content.TitleMaxLength)

	sb.WriteString("\n")
	sb.WriteString(descriptionRules)

	if len(content.BodySections) > 0 {
		sb.WriteString("\nRequested sections:\n")
		writeSectionRequests(&sb, content.BodySections)
	}
	return sb.String()
}

// writeSectionRequests lists declared sections as a bullet per section.
func writeSectionRequests(sb *strings.Builder, sections []forgeconfig.Section) {
	for _, s := range sections {
		fmt.Fprintf(sb, "- %s", s.Name)
		if s.Required {
			sb.WriteString(" (required)")
		}
		if s.Description != "" {
			sb.WriteString(": ")
			sb.WriteString(s.Description)
		}
		sb.WriteString("\n")
	}
}

// titleStubs are the fillers a model writes when it has to produce a title
// before it knows what to call the change. They are indistinguishable from a
// real title by length, so they need naming explicitly.
var titleStubs = map[string]bool{
	"placeholder":    true,
	"todo":           true,
	"tbd":            true,
	"title":          true,
	"subject":        true,
	"summary":        true,
	"commit title":   true,
	"commit message": true,
	"n/a":            true,
	"none":           true,
	"untitled":       true,
}

// stubTitle reports whether a title is filler rather than a description of the
// change. Leading and trailing punctuation is stripped before matching, so a
// stub that trails structural JSON characters — the model trying to abandon its
// answer and start over, which constrained generation renders as literal text
// inside the string — is recognised as the same thing.
func stubTitle(title string) bool {
	norm := strings.ToLower(strings.TrimFunc(title, func(r rune) bool {
		return !unicode.IsLetter(r) && !unicode.IsDigit(r)
	}))
	return titleStubs[norm]
}

// summaryProblems lists what is wrong with a returned summary in the words the
// model needs to fix it. An empty result means the summary is usable.
//
// Only three things are worth a second call: a title that does not name the
// change, a title over the configured budget, and a required section that came
// back missing or empty. All are cheap to state and cheap to fix, and none can
// be corrected on the host without inventing text.
func summaryProblems(s AgentSummary, content forgeconfig.Content) []string {
	var problems []string

	title := strings.TrimSpace(s.Title)
	switch {
	case title == "":
		problems = append(problems, "the title is empty")
	case stubTitle(title):
		problems = append(problems, fmt.Sprintf(
			"the title %q is a placeholder rather than a description of the change", title))
	}

	if n := len([]rune(title)); n > content.TitleMaxLength {
		problems = append(problems, fmt.Sprintf(
			"the title is %d characters; it must be at most %d", n, content.TitleMaxLength))
	}

	for _, declared := range content.BodySections {
		if !declared.Required {
			continue
		}
		if strings.TrimSpace(sectionContent(s.Sections, declared.Name)) == "" {
			problems = append(problems, fmt.Sprintf(
				"the required section %q is missing or empty", declared.Name))
		}
	}
	return problems
}

// retryPrompt asks for a corrected summary, naming what was wrong.
func retryPrompt(problems []string) string {
	var sb strings.Builder
	sb.WriteString("That summary cannot be used:\n")
	for _, p := range problems {
		sb.WriteString("- ")
		sb.WriteString(p)
		sb.WriteString("\n")
	}
	sb.WriteString("\nProduce the whole summary again, corrected. Keep everything else as it was.")
	return sb.String()
}

// renderBody assembles the shared body that becomes both the commit message
// body and the pull request description: the description first, then each
// declared section under its own heading.
//
// Sections render in the order they were declared, not the order they came
// back in, so the shape of a body is the repository's decision rather than the
// model's. Sections the agent returned that nobody asked for are dropped.
func renderBody(description string, declared []forgeconfig.Section, got []SummarySection) string {
	body := strings.TrimSpace(description)
	for _, d := range declared {
		content := strings.TrimSpace(sectionContent(got, d.Name))
		if content == "" {
			if !d.Required {
				continue
			}
			content = notProvided
		}
		if body != "" {
			body += "\n\n"
		}
		body += "## " + d.Name + "\n\n" + content
	}
	return body
}

// sectionContent finds a returned section by name, matched case-insensitively
// so a model that title-cases a heading still lands in the right slot.
func sectionContent(sections []SummarySection, name string) string {
	for _, s := range sections {
		if strings.EqualFold(strings.TrimSpace(s.Name), strings.TrimSpace(name)) {
			return s.Content
		}
	}
	return ""
}

// ApplyFooter appends the operator's footer to a pull request body. The footer
// is pull-request only: the commit carries trailers instead, which is where git
// tooling looks for this kind of metadata.
func ApplyFooter(body, footer string) string {
	footer = strings.TrimSpace(footer)
	if footer == "" {
		return body
	}
	if body = strings.TrimSpace(body); body == "" {
		return footer
	}
	return body + "\n\n" + footer
}

// ApplyTrailers appends git trailers to a commit message, separated from the
// body by a blank line so `git interpret-trailers` reads them as a trailer
// block.
func ApplyTrailers(message string, trailers []string) string {
	var kept []string
	for _, t := range trailers {
		if t = strings.TrimSpace(t); t != "" {
			kept = append(kept, t)
		}
	}
	if len(kept) == 0 {
		return message
	}
	if message = strings.TrimRight(message, "\n"); message == "" {
		return strings.Join(kept, "\n")
	}
	return message + "\n\n" + strings.Join(kept, "\n")
}
